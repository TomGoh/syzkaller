// Non-protected Gunyah VM. The image is one shared (or lent) parcel at GPA 0.
// fw.config.guest_phys_addr stays 0 because these helpers never call
// GH_VM_ANDROID_SET_FW_CONFIG, so gunyah_vm_is_fw_binding treats that parcel
// as the firmware binding and gunyah_gup_setup_demand_paging sends no ranges.
// Extra parcels at the SYZOS link addresses make the count non-zero. The
// manager then sibling-donates a protection extent (parent parent_ddr) onto
// a paged extent (parent the owner's DDR) and the hypervisor returns DENIED,
// which the RM reports as VM_START error 9 (MAP_FAILED).
// syz_gunyah_setup_vm shares (GH_VM_SET_USER_MEM_REGION).
// syz_gunyah_setup_vm_lend lends (GH_VM_ANDROID_LEND_USER_MEM) and marks the
// VM protected. RM auth stays AUTH_NONE. The driver's GH_VM_START installs
// the DTB parcel as the IMAGE address layout. GH_VM_SET_BOOT_CONTEXT sets
// the PC to the payload in the second page of that parcel, not to guest_main:
// guest_main is linked at the high SYZOS addresses, which are not mapped.
// The DTB's vdevices (doorbell, message-queue) are realized by the Manager
// at VM_INIT. Source of the protocol:
//   klinux drivers/virt/gunyah/vm_mgr.c gunyah_vm_start / gunyah_vm_set_boot_context
//   klinux include/uapi/linux/gunyah.h
//   futlab gunyah-resource-manager vm_firmware_vm_set_boot_context_default

